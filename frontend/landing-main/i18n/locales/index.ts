import { en } from './en';
import { SupportedLanguage } from '../types';

type DeepPartial<T> = {
  [P in keyof T]?: T[P] extends object ? DeepPartial<T[P]> : T[P];
};

// Helper to create locale overrides on top of the English baseline with fallback
function makeLocale(overrides: DeepPartial<typeof en>): typeof en {
  return {
    common: { ...en.common, ...(overrides.common || {}) } as typeof en.common,
    navigation: { ...en.navigation, ...(overrides.navigation || {}) } as typeof en.navigation,
    landing: { ...en.landing, ...(overrides.landing || {}) } as typeof en.landing,
    dashboards: { ...en.dashboards, ...(overrides.dashboards || {}) } as typeof en.dashboards,
    riskAssessment: { ...en.riskAssessment, ...(overrides.riskAssessment || {}) } as typeof en.riskAssessment,
    pipelineSteps: { ...en.pipelineSteps, ...(overrides.pipelineSteps || {}) } as typeof en.pipelineSteps,
    xai: { ...en.xai, ...(overrides.xai || {}) } as typeof en.xai,
  };
}

